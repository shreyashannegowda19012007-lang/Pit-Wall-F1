"""
Formal Uncertainty & Probabilistic Modelling Framework for Formula One Analytics.
Provides standardized representations for point estimates, probability distributions,
uncertainty types, confidence/credible intervals, data quality, and model assumptions.
"""

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Any, Tuple
import numpy as np


class UncertaintyType:
    MEASUREMENT = "MEASUREMENT_NOISE"   # Sensor precision & sampling jitter
    PARAMETER = "PARAMETER_UNCERTAINTY"   # Estimated model parameter posterior width
    PROCESS = "PROCESS_UNCERTAINTY"       # Stochastic race events (Safety Car, pit stops, traffic)
    MODEL = "MODEL_UNCERTAINTY"           # Structural model approximation error


class IntervalType:
    CREDIBLE = "CREDIBLE_INTERVAL"              # Bayesian posterior credible interval
    PREDICTION = "PREDICTION_INTERVAL"          # Range for future individual observations
    CONFIDENCE = "CONFIDENCE_INTERVAL"          # Range for frequentist parameter mean
    SIMULATION_PERCENTILE = "SIMULATION_PERCENTILE" # Empirical percentiles from Monte Carlo


class DataProvenance:
    OBSERVED = "OBSERVED"     # Directly from telemetry or timing without modification
    MODELLED = "MODELLED"     # Generated by an ML or statistical model
    SIMULATED = "SIMULATED"   # Result of Monte Carlo or physical simulation
    ASSUMED = "ASSUMED"       # Hard-coded or heuristic baseline estimate


@dataclass
class ProbabilisticPrediction:
    """
    Standardized container for any statistical or simulation prediction.
    Enforces explicit representation of uncertainty, distributions, bounds, and assumptions.
    """
    point_estimate: float
    unit: str
    distribution_type: str                  # "NORMAL", "LOGNORMAL", "DISCRETE_EMPIRICAL", "BAYESIAN_POSTERIOR"
    mean: float
    median: float
    std_dev: Optional[float]
    lower_bound: float                       # e.g., P10 or lower credible bound
    upper_bound: float                       # e.g., P90 or upper credible bound
    interval_pct: float = 0.95               # Default 95% interval
    interval_type: str = IntervalType.PREDICTION
    sample_size: int = 10000
    model_name: str = "UncertaintyEngine"
    model_version: str = "v2.4.0"
    data_quality: str = "HIGH"               # "HIGH", "MEDIUM", "LOW"
    provenance: str = DataProvenance.MODELLED
    assumptions: List[str] = field(default_factory=list)
    probabilities_map: Optional[Dict[str, float]] = field(default_factory=dict)
    uncertainty_types: List[str] = field(default_factory=lambda: [UncertaintyType.PROCESS, UncertaintyType.PARAMETER])

    def format_summary(self) -> str:
        """Formats clean engineering string e.g. '4.1 ± 1.7 [95% Range: 2.4 - 5.8]'."""
        return f"{self.point_estimate:.1f} ± {self.std_dev:.1f} [{int(self.interval_pct*100)}% {self.interval_type}: {self.lower_bound:.1f} - {self.upper_bound:.1f} {self.unit}]"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "point_estimate": round(self.point_estimate, 3),
            "unit": self.unit,
            "distribution_type": self.distribution_type,
            "mean": round(self.mean, 3),
            "median": round(self.median, 3),
            "std_dev": round(self.std_dev, 3) if self.std_dev is not None else None,
            "lower_bound": round(self.lower_bound, 3),
            "upper_bound": round(self.upper_bound, 3),
            "interval_pct": self.interval_pct,
            "interval_type": self.interval_type,
            "sample_size": self.sample_size,
            "model_name": self.model_name,
            "model_version": self.model_version,
            "data_quality": self.data_quality,
            "provenance": self.provenance,
            "assumptions": self.assumptions,
            "probabilities_map": self.probabilities_map,
            "uncertainty_types": self.uncertainty_types,
            "summary_text": self.format_summary()
        }


def validate_probability_vector(probs_map: Dict[str, float], tolerance: float = 1e-4) -> Tuple[bool, float]:
    """
    Validates that a discrete probability distribution maps to non-negative values and sums to 1.0 within tolerance.
    Returns (is_valid, total_sum).
    """
    if not probs_map:
        return False, 0.0

    vals = np.array(list(probs_map.values()))
    if (vals < -tolerance).any():
        return False, float(np.sum(vals))

    total_sum = float(np.sum(vals))
    is_valid = abs(total_sum - 1.0) <= tolerance
    return is_valid, total_sum

